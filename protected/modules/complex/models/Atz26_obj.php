    public function get_addr($type=null) {
        $addresses = Atz26_adr::model()->findAllByAttributes(['id_obj' => $this->id]);
        $result = '';      
        foreach($addresses as $address) {
            if($address->nas_punkt) $nas_punkt = $address->nas_punkt_type_link->naim_gor.', '.$address->nas_punkt.', ';
            else $nas_punkt = '';
            if($address->street) $street = $address->street_type_link->naim_ul.' '.$address->street.', ';
            else $street = '';
            if($type = 1) $result = $result.$address->obj->report->est->est_name.' ('.$address->obj_name.'), '.$address->obj_index.', '.$address->mun_link->naim_mun.', '.$nas_punkt.$street.' д.'.$address->dom.', '.$address->kad_num.';';
            else $result = $result.$address->obj_name.', '.$address->obj_index.', '.$address->mun_link->naim_mun.', '.$nas_punkt.$street.' д.'.$address->dom.', '.$address->kad_num.'<br>';
        }
        return $result;
    }
    
