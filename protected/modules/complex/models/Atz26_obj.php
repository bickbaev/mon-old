    public function sum_field($id_rep_type, $pok1, $pok4, $est_id, $field) {
        $criteria = new CDbCriteria();
        $criteria->select = "t.$field";
        $criteria->condition = 't.pok1 = :pok1 AND t.pok4 = :pok4';
        $criteria->params = [':pok1' => $pok1, ':pok4' => $pok4];

        if($est_id == 1) {                
            $criteria->with = [
                'report' => [
                    'condition' => 'report.id_rep_type = '.$id_rep_type
                ]
            ];
        } else {
            $criteria->with = [
                'report' => [
                    'with' => [
                        'est' => [
                            'condition' => 'est.id_okr = '.$est_id
                        ]
                    ],
                    'condition' => 'report.id_rep_type = '.$id_rep_type
                ]
            ];                    
        }

        $records = $this->findAll($criteria);
        $sum = 0;
        foreach($records as $record) {
            $sum += $record->$field;
        }
        return $sum;
    }
    
